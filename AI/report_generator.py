def _findings_table(all_findings: list[dict] | None) -> Table | None:
    if not all_findings:
        return None
    data = [["Condition", "Probability", "Status", "Urgency"]]
    for f in all_findings[:8]:
        data.append([
            f.get("condition", "—"),
            f"{f.get('probability', 0) * 100:.1f}%",
            f.get("status", "—").title(),
            f.get("urgency", "—").title(),
        ])
    table = Table(data, colWidths=[2.2 * inch, 1.2 * inch, 1.3 * inch, 1.8 * inch])
    table.setStyle(TableStyle([
        ("BACKGROUND", (0, 0), (-1, 0), colors.HexColor("#0f4c81")),
        ("TEXTCOLOR", (0, 0), (-1, 0), colors.white),
        ("FONTNAME", (0, 0), (-1, 0), "Helvetica-Bold"),
        ("FONTSIZE", (0, 0), (-1, -1), 9),
        ("GRID", (0, 0), (-1, -1), 0.5, colors.HexColor("#cbd5e1")),
        ("ROWBACKGROUNDS", (0, 1), (-1, -1), [colors.white, colors.HexColor("#f8fafc")]),
        ("LEFTPADDING", (0, 0), (-1, -1), 6),
        ("TOPPADDING", (0, 0), (-1, -1), 5),
        ("BOTTOMPADDING", (0, 0), (-1, -1), 5),
    ]))
    return table


def generate_report(
    primary_label: str,
    confidence: float,
    severity: str | None,
    differential: list[dict],
    output_dir: str,
    study_id: int,
    all_findings: list[dict] | None = None,
    extra: str = "",
    modality: str = "XR",
    patient_name: str | None = None,
    patient_age: int | None = None,
    patient_gender: str | None = None,
    model_version: str | None = None,
    uncertainty_level: str | None = None,
    original_filename: str | None = None,
    study_date: datetime | None = None,
) -> dict:
    key = primary_label if primary_label in FINDINGS_TEMPLATES else (
        "Pneumonia" if any(w in primary_label.lower() for w in ("pneumonia", "opacity", "consolidation")) else "Normal"
    )

    findings = FINDINGS_TEMPLATES.get(key, FINDINGS_TEMPLATES["Normal"])
    if extra:
        findings += f" {extra}"
    if all_findings and len(all_findings) > 1:
        secondary = [f["condition"] for f in all_findings[1:3] if f.get("status") in ("detected", "possible")]
        if secondary:
            findings += f" Secondary considerations: {', '.join(secondary)}."

    impression = IMPRESSION_TEMPLATES.get(key, IMPRESSION_TEMPLATES["Normal"])
    impression += _severity_note(severity)
    impression += f" AI confidence: {confidence * 100:.1f}%."
    impression += _findings_note(all_findings)

    meta = {
        "study_id": study_id,
        "patient_name": patient_name or "Not recorded",
        "patient_age": patient_age if patient_age is not None else "—",
        "patient_gender": (patient_gender or "—").upper() if patient_gender else "—",
        "modality_label": modality,
        "exam_title": MODALITY_TITLES.get(modality, modality),
        "accession": f"RAI-{study_id:06d}",
        "filename": original_filename or "—",
        "report_date": (study_date or datetime.utcnow()).strftime("%d %b %Y %H:%M UTC"),
    }

    pdf_path = _export_pdf(
        findings=findings,
        impression=impression,
        output_dir=output_dir,
        study_id=study_id,
        all_findings=all_findings,
        modality=modality,
        meta=meta,
        primary_label=primary_label,
        confidence=confidence,
        model_version=model_version,
        uncertainty_level=uncertainty_level,
    )

    return {"findings": findings, "impression": impression, "pdf_path": pdf_path}


def _export_pdf(
    findings,
    impression,
    output_dir,
    study_id,
    all_findings=None,
    modality="XR",
    meta=None,
    primary_label="",
    confidence=0.0,
    model_version=None,
    uncertainty_level=None,
):
    out_path = Path(output_dir) / f"report_{study_id}.pdf"
    doc = SimpleDocTemplate(
        str(out_path),
        pagesize=letter,
        leftMargin=0.75 * inch,
        rightMargin=0.75 * inch,
        topMargin=0.65 * inch,
        bottomMargin=0.65 * inch,
    )
    styles = _build_styles()
    meta = meta or {}

    story = [
        Paragraph(INSTITUTION, styles["title"]),
        Paragraph(SUBTITLE, styles["subtitle"]),
        HRFlowable(width="100%", thickness=1, color=colors.HexColor("#0f4c81")),
        Spacer(1, 10),
        Paragraph(f"<b>RADIOLOGY REPORT — {MODALITY_TITLES.get(modality, modality).upper()}</b>", styles["section"]),
        Spacer(1, 4),
        _patient_table(meta, styles),
        Spacer(1, 12),
        Paragraph("AI ANALYSIS SUMMARY", styles["section"]),
        _ai_summary_table(primary_label, confidence, model_version, uncertainty_level, styles),
        Spacer(1, 12),
        Paragraph("CLINICAL INDICATION", styles["section"]),
        Paragraph(
            "AI-assisted preliminary interpretation for triage and clinical decision support. "
            "Referral for chest imaging evaluation.",
            styles["body"],
        ),
        Spacer(1, 8),
        Paragraph("TECHNIQUE", styles["section"]),
        Paragraph(MODALITY_TECHNIQUE.get(modality, "Medical imaging study."), styles["body"]),
        Spacer(1, 8),
        Paragraph("COMPARISON", styles["section"]),
        Paragraph("No prior studies available for comparison at time of report generation.", styles["body"]),
        Spacer(1, 8),
        Paragraph("FINDINGS", styles["section"]),
        Paragraph(findings, styles["body"]),
        Spacer(1, 8),
    ]

    table = _findings_table(all_findings)
    if table:
        story += [Paragraph("DETECTED CONDITIONS (AI)", styles["section"]), table, Spacer(1, 8)]

    story += [
        Paragraph("IMPRESSION", styles["section"]),
        Paragraph(f"<b>{primary_label}</b> — {impression}", styles["body"]),
        Spacer(1, 8),
        Paragraph("RECOMMENDATIONS", styles["section"]),
        Paragraph(
            "1. Correlate with clinical history and physical examination.<br/>"
            "2. Review AI Grad-CAM heatmap for explainability.<br/>"
            "3. Obtain formal radiologist sign-off before clinical action.<br/>"
            "4. Repeat imaging or advanced studies as clinically indicated.",
            styles["body"],
        ),
        Spacer(1, 16),
        HRFlowable(width="100%", thickness=0.5, color=colors.HexColor("#cbd5e1")),
        Spacer(1, 8),
        Paragraph(
            "<b>Electronically generated report</b> — Awaiting radiologist verification<br/>"
            "Reporting Physician: _________________________ &nbsp;&nbsp; Date: ______________",
            styles["small"],
        ),
        Spacer(1, 10),
        Paragraph(DISCLAIMER, styles["disclaimer"]),
    ]

    doc.build(story)
    return str(out_path)
