def _ai_summary_table(primary_label, confidence, model_version, uncertainty, styles) -> Table:
    rows = [
        ["Primary Finding", primary_label],
        ["AI Confidence", f"{confidence * 100:.1f}%"],
        ["Uncertainty", uncertainty or "—"],
        ["Model", (model_version or "AI Engine")[:60]],
    ]
    table = Table(rows, colWidths=[1.5 * inch, 5.0 * inch])
    table.setStyle(TableStyle([
        ("BACKGROUND", (0, 0), (0, -1), colors.HexColor("#eff6ff")),
        ("FONTNAME", (0, 0), (0, -1), "Helvetica-Bold"),
        ("FONTSIZE", (0, 0), (-1, -1), 9),
        ("GRID", (0, 0), (-1, -1), 0.5, colors.HexColor("#bfdbfe")),
        ("LEFTPADDING", (0, 0), (-1, -1), 8),
        ("TOPPADDING", (0, 0), (-1, -1), 5),
        ("BOTTOMPADDING", (0, 0), (-1, -1), 5),
    ]))
