def _severity_note(severity: str | None) -> str:
    notes = {
        "mild": " Severity: mild.",
        "moderate": " Severity: moderate.",
        "severe": " Severity: severe — urgent attention advised.",
    }
    return notes.get(severity, "")


def _findings_note(all_findings: list[dict] | None) -> str:
    if not all_findings or len(all_findings) <= 1:
        return ""
    others = [f"{f['condition']} ({f['probability'] * 100:.0f}%)" for f in all_findings[1:4]]
    return " Additional considerations: " + ", ".join(others) + "."


